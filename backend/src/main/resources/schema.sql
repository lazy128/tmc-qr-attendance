CREATE TABLE IF NOT EXISTS access_attempt (
  event_id VARCHAR(100) PRIMARY KEY,
  correlation_id VARCHAR(100),
  employee_id VARCHAR(120),
  site_id VARCHAR(100),
  station_id VARCHAR(100),
  direction VARCHAR(10),
  scanned_at TIMESTAMP WITH TIME ZONE,
  received_at TIMESTAMP WITH TIME ZONE,
  credential_id VARCHAR(120),
  credential_version INT,
  jti VARCHAR(160),
  decision VARCHAR(10),
  reason_code VARCHAR(50),
  command_state VARCHAR(20),
  passage_state VARCHAR(30),
  offline_accepted BOOLEAN,
  evidence VARCHAR(30),
  suspicious BOOLEAN
);

CREATE TABLE IF NOT EXISTS used_token (
  site_id VARCHAR(100),
  jti VARCHAR(160),
  event_id VARCHAR(100),
  consumed_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (site_id, jti)
);

CREATE TABLE IF NOT EXISTS edge_outbox (
  event_id VARCHAR(100) PRIMARY KEY,
  payload VARCHAR(4000),
  status VARCHAR(20) DEFAULT 'PENDING',
  central_status VARCHAR(20) DEFAULT 'PENDING',
  attendance_status VARCHAR(20) DEFAULT 'PENDING',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE edge_outbox ADD COLUMN IF NOT EXISTS central_status VARCHAR(20) DEFAULT 'PENDING';
ALTER TABLE edge_outbox ADD COLUMN IF NOT EXISTS attendance_status VARCHAR(20) DEFAULT 'PENDING';

CREATE TABLE IF NOT EXISTS audit_lock (id INT PRIMARY KEY);
MERGE INTO audit_lock KEY(id) VALUES (1);

CREATE TABLE IF NOT EXISTS edge_audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor VARCHAR(120),
  action VARCHAR(80),
  target VARCHAR(160),
  result VARCHAR(30),
  correlation_id VARCHAR(120),
  occurred_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  previous_hash VARCHAR(128),
  entry_hash VARCHAR(128)
);

ALTER TABLE edge_audit ADD COLUMN IF NOT EXISTS hash_version INT DEFAULT 1;

CREATE TABLE IF NOT EXISTS idempotency_request (
  event_id VARCHAR(100) PRIMARY KEY,
  jti VARCHAR(160),
  request_fingerprint VARCHAR(64),
  state VARCHAR(20) NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE idempotency_request ADD COLUMN IF NOT EXISTS request_fingerprint VARCHAR(64);

CREATE TABLE IF NOT EXISTS attendance_record (
  event_id VARCHAR(100) PRIMARY KEY,
  employee_id VARCHAR(120),
  site_id VARCHAR(100),
  station_id VARCHAR(100),
  direction VARCHAR(10),
  scanned_at TIMESTAMP WITH TIME ZONE,
  command_state VARCHAR(20),
  passage_state VARCHAR(30),
  evidence VARCHAR(30),
  eligible BOOLEAN,
  hr_review BOOLEAN,
  suspicious BOOLEAN
);

CREATE TABLE IF NOT EXISTS credential (
  credential_id VARCHAR(120) PRIMARY KEY,
  employee_id VARCHAR(120) NOT NULL,
  version INT NOT NULL,
  active BOOLEAN NOT NULL,
  device_hash VARCHAR(256)
);

CREATE TABLE IF NOT EXISTS employee_presence (
  site_id VARCHAR(100),
  employee_id VARCHAR(120),
  direction VARCHAR(10),
  event_id VARCHAR(100),
  evidence_quality VARCHAR(30),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (site_id, employee_id)
);

CREATE TABLE IF NOT EXISTS device_binding (
  credential_id VARCHAR(120) PRIMARY KEY REFERENCES credential(credential_id),
  device_hash VARCHAR(256) NOT NULL,
  proof_hash VARCHAR(64) NOT NULL
);

CREATE TABLE IF NOT EXISTS station_registry (
  station_id VARCHAR(100) PRIMARY KEY,
  site_id VARCHAR(100) NOT NULL,
  gate_id VARCHAR(100) NOT NULL,
  status VARCHAR(20) NOT NULL,
  last_heartbeat_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS hr_export_batch (
  period VARCHAR(7) PRIMARY KEY,
  csv_payload CLOB NOT NULL,
  ready_at TIMESTAMP WITH TIME ZONE NOT NULL,
  sent_at TIMESTAMP WITH TIME ZONE NOT NULL,
  acknowledged_at TIMESTAMP WITH TIME ZONE NOT NULL
);
