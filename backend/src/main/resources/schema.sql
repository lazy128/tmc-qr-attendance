CREATE TABLE IF NOT EXISTS access_attempt (
  event_id VARCHAR(100) PRIMARY KEY,
  correlation_id VARCHAR(100),
  employee_id VARCHAR(120),
  site_id VARCHAR(100),
  station_id VARCHAR(100),
  direction VARCHAR(10),
  scanned_at TIMESTAMP WITH TIME ZONE,
  received_at TIMESTAMP WITH TIME ZONE,
  credential_id VARCHAR(120),
  credential_version INT,
  jti VARCHAR(160),
  decision VARCHAR(10),
  reason_code VARCHAR(50),
  command_state VARCHAR(20),
  passage_state VARCHAR(30),
  offline_accepted BOOLEAN,
  evidence VARCHAR(30),
  suspicious BOOLEAN
);

CREATE TABLE IF NOT EXISTS used_token (
  site_id VARCHAR(100),
  jti VARCHAR(160),
  event_id VARCHAR(100),
  consumed_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (site_id, jti)
);

CREATE TABLE IF NOT EXISTS edge_outbox (
  event_id VARCHAR(100) PRIMARY KEY,
  payload VARCHAR(4000),
  status VARCHAR(20) DEFAULT 'PENDING',
  central_status VARCHAR(20) DEFAULT 'PENDING',
  attendance_status VARCHAR(20) DEFAULT 'PENDING',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE edge_outbox ADD COLUMN IF NOT EXISTS central_status VARCHAR(20) DEFAULT 'PENDING';
ALTER TABLE edge_outbox ADD COLUMN IF NOT EXISTS attendance_status VARCHAR(20) DEFAULT 'PENDING';

CREATE TABLE IF NOT EXISTS audit_lock (id INT PRIMARY KEY);
MERGE INTO audit_lock KEY(id) VALUES (1);

CREATE TABLE IF NOT EXISTS edge_audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor VARCHAR(120),
  action VARCHAR(80),
  target VARCHAR(160),
  result VARCHAR(30),
  correlation_id VARCHAR(120),
  occurred_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  previous_hash VARCHAR(128),
  entry_hash VARCHAR(128)
);

ALTER TABLE edge_audit ADD COLUMN IF NOT EXISTS hash_version INT DEFAULT 1;

CREATE TABLE IF NOT EXISTS idempotency_request (
  event_id VARCHAR(100) PRIMARY KEY,
  jti VARCHAR(160),
  request_fingerprint VARCHAR(64),
  state VARCHAR(20) NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE idempotency_request ADD COLUMN IF NOT EXISTS request_fingerprint VARCHAR(64);

CREATE TABLE IF NOT EXISTS attendance_record (
  event_id VARCHAR(100) PRIMARY KEY,
  employee_id VARCHAR(120),
  site_id VARCHAR(100),
  station_id VARCHAR(100),
  direction VARCHAR(10),
  scanned_at TIMESTAMP WITH TIME ZONE,
  command_state VARCHAR(20),
  passage_state VARCHAR(30),
  evidence VARCHAR(30),
  eligible BOOLEAN,
  hr_review BOOLEAN,
  suspicious BOOLEAN
);

CREATE TABLE IF NOT EXISTS credential (
  credential_id VARCHAR(120) PRIMARY KEY,
  employee_id VARCHAR(120) NOT NULL,
  version INT NOT NULL,
  active BOOLEAN NOT NULL,
  device_hash VARCHAR(256)
);

CREATE TABLE IF NOT EXISTS employee_presence (
  site_id VARCHAR(100),
  employee_id VARCHAR(120),
  direction VARCHAR(10),
  event_id VARCHAR(100),
  evidence_quality VARCHAR(30),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (site_id, employee_id)
);

CREATE TABLE IF NOT EXISTS device_binding (
  credential_id VARCHAR(120) PRIMARY KEY REFERENCES credential(credential_id),
  device_hash VARCHAR(256) NOT NULL,
  proof_hash VARCHAR(64) NOT NULL
);

CREATE TABLE IF NOT EXISTS station_registry (
  station_id VARCHAR(100) PRIMARY KEY,
  site_id VARCHAR(100) NOT NULL,
  gate_id VARCHAR(100) NOT NULL,
  status VARCHAR(20) NOT NULL,
  last_heartbeat_at TIMESTAMP WITH TIME ZONE
);
ALTER TABLE station_registry ADD COLUMN IF NOT EXISTS display_name VARCHAR(150);
ALTER TABLE station_registry ADD COLUMN IF NOT EXISTS gate_type VARCHAR(24) DEFAULT 'ATTENDANCE_GATE' NOT NULL;
ALTER TABLE station_registry ADD COLUMN IF NOT EXISTS allowed_groups VARCHAR(80) DEFAULT 'STAFF,MANAGER,EXECUTIVE' NOT NULL;
ALTER TABLE station_registry ADD COLUMN IF NOT EXISTS directions VARCHAR(24) DEFAULT 'ENTRY,EXIT' NOT NULL;
ALTER TABLE station_registry ADD COLUMN IF NOT EXISTS opens_at TIME;
ALTER TABLE station_registry ADD COLUMN IF NOT EXISTS closes_at TIME;
ALTER TABLE access_attempt ADD COLUMN IF NOT EXISTS attendance_gate BOOLEAN DEFAULT TRUE NOT NULL;
CREATE INDEX IF NOT EXISTS idx_access_pending_scan ON access_attempt (site_id, employee_id, attendance_gate, command_state);

CREATE INDEX IF NOT EXISTS idx_attendance_employee_time ON attendance_record(employee_id, scanned_at);

CREATE TABLE IF NOT EXISTS daily_timesheet (
  employee_id VARCHAR(120) NOT NULL,
  work_date DATE NOT NULL,
  site_id VARCHAR(100) NOT NULL,
  first_in TIMESTAMP WITH TIME ZONE,
  last_out TIMESTAMP WITH TIME ZONE,
  worked_minutes BIGINT NOT NULL,
  status VARCHAR(24) NOT NULL,
  review_flag BOOLEAN NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  PRIMARY KEY(employee_id, work_date)
);

CREATE TABLE IF NOT EXISTS timesheet_day_lock (
  employee_id VARCHAR(120) NOT NULL,
  work_date DATE NOT NULL,
  PRIMARY KEY(employee_id, work_date)
);

CREATE TABLE IF NOT EXISTS timesheet_adjustment (
  employee_id VARCHAR(120) NOT NULL,
  work_date DATE NOT NULL,
  exit_at TIMESTAMP WITH TIME ZONE NOT NULL,
  justification VARCHAR(300) NOT NULL,
  actor VARCHAR(120) NOT NULL,
  PRIMARY KEY(employee_id, work_date)
);

CREATE TABLE IF NOT EXISTS timesheet_publication (
  period VARCHAR(7) PRIMARY KEY,
  revision BIGINT NOT NULL,
  status VARCHAR(12) NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE,
  next_attempt TIMESTAMP WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS hr_export_batch (
  period VARCHAR(7) PRIMARY KEY,
  csv_payload CLOB NOT NULL,
  ready_at TIMESTAMP WITH TIME ZONE NOT NULL,
  sent_at TIMESTAMP WITH TIME ZONE NOT NULL,
  acknowledged_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS workplace_employee (
  employee_id VARCHAR(60) PRIMARY KEY,
  full_name VARCHAR(120) NOT NULL,
  site_id VARCHAR(100) NOT NULL,
  department_id VARCHAR(60) NOT NULL,
  access_group VARCHAR(16) NOT NULL,
  shift_id VARCHAR(16) NOT NULL,
  credential_id VARCHAR(120) NOT NULL UNIQUE REFERENCES credential(credential_id)
);

CREATE TABLE IF NOT EXISTS workplace_account (
  username VARCHAR(60) PRIMARY KEY,
  password_hash VARCHAR(180) NOT NULL,
  role VARCHAR(16) NOT NULL,
  employee_id VARCHAR(60) UNIQUE REFERENCES workplace_employee(employee_id),
  station_id VARCHAR(100) REFERENCES station_registry(station_id),
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  change_required BOOLEAN NOT NULL DEFAULT TRUE,
  failed_attempts INT NOT NULL DEFAULT 0,
  locked_until TIMESTAMP WITH TIME ZONE,
  security_version INT NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS workplace_session (
  session_id VARCHAR(36) PRIMARY KEY,
  username VARCHAR(60) NOT NULL REFERENCES workplace_account(username),
  security_version INT NOT NULL,
  expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_workplace_session_expiry ON workplace_session(expires_at);
CREATE INDEX IF NOT EXISTS idx_workplace_session_user ON workplace_session(username, expires_at);

CREATE TABLE IF NOT EXISTS workplace_login_history (
  session_id VARCHAR(36) PRIMARY KEY,
  username VARCHAR(60) NOT NULL REFERENCES workplace_account(username),
  signed_in_at TIMESTAMP WITH TIME ZONE NOT NULL,
  device_label VARCHAR(80) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_workplace_login_history_user ON workplace_login_history(username, signed_in_at);
ALTER TABLE workplace_login_history ADD COLUMN IF NOT EXISTS device_id VARCHAR(36);
ALTER TABLE workplace_login_history ADD COLUMN IF NOT EXISTS client_ip VARCHAR(45);
CREATE TABLE IF NOT EXISTS workplace_browser_device (
  username VARCHAR(60) NOT NULL REFERENCES workplace_account(username),
  device_id VARCHAR(36) NOT NULL,
  display_name VARCHAR(60),
  PRIMARY KEY (username, device_id)
);
